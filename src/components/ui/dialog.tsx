"use client"

/**
 * dialog.tsx – Dialog primitive
 * Reusable shadcn/ui-style modal built on @radix-ui/react-dialog: portals an
 * animated overlay plus a centered content panel; used for site-wide modals
 * and forms.
 */

import * as React from "react"
import * as DialogPrimitive from "@radix-ui/react-dialog"
import { XIcon } from "lucide-react"

import { cn } from "@/lib/utils"

/**
 * Dialog – Radix dialog root (controls open/closed state).
 * Wraps the shadcn/ui modal used for site-wide overlays and forms.
 */
function Dialog({
  ...props
}: React.ComponentProps<typeof DialogPrimitive.Root>) {
  return <DialogPrimitive.Root data-slot="dialog" {...props} />
}

/**
 * DialogTrigger – element that opens the dialog when activated.
 */
function DialogTrigger({
  ...props
}: React.ComponentProps<typeof DialogPrimitive.Trigger>) {
  return <DialogPrimitive.Trigger data-slot="dialog-trigger" {...props} />
}

/**
 * DialogPortal – mounts the dialog into a portal so it renders above the
 * page regardless of the parent's stacking context.
 */
function DialogPortal({
  ...props
}: React.ComponentProps<typeof DialogPrimitive.Portal>) {
  return <DialogPrimitive.Portal data-slot="dialog-portal" {...props} />
}

